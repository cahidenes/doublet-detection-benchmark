"""Build report/data.md: every number behind the report as readable Markdown tables.

Run the other analysis scripts first (they write results/stats/*.tsv), then:
    python analysis/make_report_data.py
"""
import pandas as pd

from style import NAMES, ROOT, STATS, TECH, main_metrics

R = ROOT / "results"
d = main_metrics()
ranks = pd.read_csv(STATS / "ranks.tsv", sep="\t", index_col=0)
ORDER = list(ranks.index)                                   # tools by mean AUPRC rank
DS = sorted(d.dataset.unique(), key=lambda s: (list(dict.fromkeys(TECH.values())).index(TECH[s]), s))


def md(df, fmt="{:.3f}", index=True):
    """DataFrame -> GitHub Markdown table (no tabulate dependency)."""
    df = df.copy()
    if index:
        df = df.reset_index()
    def cell(v):
        if isinstance(v, float):
            return "–" if pd.isna(v) else fmt.format(v)
        return str(v)
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join("---" if df[c].dtype == object else "--:" for c in df.columns) + "|"
    rows = ["| " + " | ".join(cell(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows])


def tool_by_ds(col, fmt="{:.3f}", agg="mean", src=d):
    m = src.pivot(index="tool", columns="dataset", values=col).reindex(index=ORDER, columns=DS)
    m[agg] = getattr(m, agg)(axis=1)
    m.index = [NAMES[t] for t in m.index]; m.index.name = "tool"
    return md(m, fmt)


out = ["# Report data",
       "",
       "Every number in [`report.md`](report.md), as tables. This file is generated by "
       "`analysis/make_report_data.py` from the TSVs in `results/`. Do not edit it by hand.",
       "Main run: every method at its defaults, the labeled doublet rate as input, seed 0. "
       "Tools are listed by mean AUPRC rank.",
       "",
       "## Contents",
       "1. [Datasets](#1-datasets) · 2. [AUPRC](#2-auprc) · 3. [AUROC](#3-auroc) · "
       "4. [Fixed identification rates](#4-fixed-identification-rates) · "
       "5. [Default calls](#5-default-calls) · 6. [Rate estimation](#6-rate-estimation) · "
       "7. [Rate robustness](#7-rate-robustness) · 8. [Runtime and memory](#8-runtime-and-memory) · "
       "9. [Scaling](#9-scaling) · 10. [Agreement](#10-agreement) · "
       "11. [Statistics](#11-statistics) · 12. [DoubletFinder pK](#12-doubletfinder-pk-sensitivity) · "
       "13. [Failed runs](#13-failed-runs) · 14. [Raw files](#14-raw-files)", ""]

# 1 datasets
ds = d.groupby("dataset").agg(droplets=("n", "first"), rate=("true_rate", "first")).loc[DS]
ds.insert(0, "technology", [TECH[x] for x in ds.index])
ds["doublets"] = (ds.droplets * ds.rate).round().astype(int)
ds["droplets"] = ds.droplets.astype(int)
out += ["## 1. Datasets", "", md(ds[["technology", "droplets", "doublets", "rate"]]), ""]

# 2-3 AUPRC / AUROC
out += ["## 2. AUPRC", "", "The last column is the mean over the 16 datasets.", "",
        tool_by_ds("auprc"), ""]
out += ["## 3. AUROC", "", tool_by_ds("auroc"), ""]
r = ranks.copy(); r.index = [NAMES[t] for t in r.index]; r.index.name = "tool"
out += ["### Summary and mean ranks (1 = best)", "", md(r), ""]

# 4 identification rates
ident = pd.read_csv(STATS / "identification.tsv", sep="\t", index_col=0).loc[ORDER]
ident.index = [NAMES[t] for t in ident.index]; ident.index.name = "tool"
out += ["## 4. Fixed identification rates",
        "",
        "These are medians over datasets. At an identification rate of x%, the top x% of droplets "
        "by score are called doublets.",
        "", md(ident), ""]

# 5 default calls
call_tools = [t for t in ORDER if d[d.tool == t].f1_default.notna().any()]
dc = d[d.tool.isin(call_tools)].groupby("tool")[["precision_default", "recall_default",
                                                   "f1_default"]].median().loc[call_tools]
dc.index = [NAMES[t] for t in dc.index]; dc.index.name = "tool"
out += ["## 5. Default calls",
        "",
        "Each tool's own threshold. Library size, # genes and DoubletDensity give scores only and "
        "are not listed. Medians over datasets:",
        "", md(dc), "", "### F1 per dataset", "",
        tool_by_ds("f1_default", agg="median", src=d[d.tool.isin(call_tools)])
        .replace("| mean |", "| median |"), ""]

# 6 rate estimation
re_ = pd.read_csv(STATS / "rate_estimation.tsv", sep="\t")
re_["tool"] = re_.tool.map(NAMES)
out += ["## 6. Rate estimation",
        "",
        "The estimated rate is called doublets ÷ droplets, and the error is estimated minus "
        "labeled. Rows marked *supplied* were given the labeled rate as input.",
        "", md(re_, index=False), "", "### Estimated rate per dataset", "",
        tool_by_ds("est_rate", agg="median", src=d[d.tool.isin(call_tools)])
        .replace("| mean |", "| median |"), ""]

# 7 robustness
rob = pd.read_csv(R / "robustness_summary.tsv", sep="\t")
cols = ["tool", "rate_mult"] + [c for c in rob.columns if c.endswith("_median")] + ["n_datasets"]
rob = rob[cols].copy(); rob["tool"] = rob.tool.map(NAMES); rob["rate_mult"] = rob.rate_mult.map(lambda x: f"{x:g}×")
rob.columns = [c.replace("_median", "") for c in rob.columns]
out += ["## 7. Rate robustness",
        "",
        "Medians over datasets. The tool is given 0.5×, 1× or 2× the labeled rate. Chord's rows "
        "use 14 datasets because it fails at 2× on the two datasets whose rate is above 0.3.",
        "", md(rob, index=False), ""]

# 8 runtime / memory main run
d["mem_gb"] = d.max_rss_mb / 1024
out += ["## 8. Runtime and memory",
        "",
        "Main run, 4 threads per job, with up to 2 jobs running at once, so treat these as "
        "approximate. Section 9 has clean, one-at-a-time timings.",
        "", "### Wall time (s)", "", tool_by_ds("wall_s", "{:.0f}", "median"), "",
        "### Peak memory (GB)", "", tool_by_ds("mem_gb", "{:.1f}", "max")
        .replace("| median |", "| max |"), ""]

# 9 scaling
sc = pd.read_csv(R / "scaling_metrics.tsv", sep="\t")
sc["n_cells"] = sc.dataset.str.extract(r"-n(\d+)$")[0].astype(int)
sc = sc[sc.status == "ok"]
for col, title, fmt in (("wall_s", "Wall time (s)", "{:.0f}"), ("max_rss_mb", "Peak memory (GB)", "{:.1f}")):
    m = sc.pivot(index="tool", columns="n_cells", values=col)
    if col == "max_rss_mb":
        m = m / 1024
    m = m.loc[[t for t in ORDER if t in m.index]]
    m.index = [NAMES[t] for t in m.index]; m.index.name = "tool"
    m.columns = [f"{c:,}" for c in m.columns]
    if col == "wall_s":
        out += ["## 9. Scaling", "", "These are nested, stratified subsamples of HMEC-orig-MULTI, "
                "run one job at a time with 4 threads.", ""]
    out += [f"### {title}", ""]
    out += [md(m, fmt), ""]
ss = pd.read_csv(R / "scaling_summary.tsv", sep="\t"); ss["tool"] = ss.tool.map(NAMES)
out += ["### Fitted exponents",
        "",
        "`time_exponent` is the slope of log(time) against log(droplets) for n ≥ 5k "
        "(1 = linear).", "", md(ss, index=False), ""]

# 10 agreement
for f, title in (("agreement_spearman", "Spearman correlation of scores"),
                 ("agreement_topk_jaccard", "Jaccard overlap of top-k droplets (k = labeled doublets)")):
    m = pd.read_csv(STATS / f"{f}.tsv", sep="\t", index_col=0).loc[ORDER, ORDER]
    m.index = [NAMES[t] for t in m.index]; m.columns = [NAMES[t] for t in m.columns]
    m.index.name = "tool"
    out += ["## 10. Agreement" if "spearman" in f else "", f"### {title} (mean over datasets)",
            "", md(m, "{:.2f}"), ""]
hd = pd.read_csv(STATS / "hard_doublets.tsv", sep="\t").set_index("dataset").loc[DS]
out += ["### Hard doublets",
        "",
        "`best_single_recall` is the best single tool's recall in its top k. "
        "`oracle_union_recall` is the share of doublets found by at least one non-baseline tool "
        "(an upper bound, since the union calls more than k droplets). `hard_fraction` is the "
        "share found by none.",
        "", md(hd), ""]

# 11 statistics
fr = pd.read_csv(STATS / "friedman.tsv", sep="\t")
out += ["## 11. Statistics", "", "### Friedman test (blocks = 16 datasets, 13 methods)", "",
        md(fr, "{:.3g}", index=False), ""]
for metric in ("auprc", "auroc"):
    pw = pd.read_csv(STATS / f"pairwise_{metric}.tsv", sep="\t")
    pw["tool_a"] = pw.tool_a.map(NAMES); pw["tool_b"] = pw.tool_b.map(NAMES)
    pw = pw.sort_values("p_holm")
    out += [f"### Pairwise Wilcoxon signed-rank, {metric.upper()} "
            f"({pw.significant.sum()} of {len(pw)} pairs with Holm p < 0.05)", "",
            "`cliffs_delta` > 0 means tool_a is higher. All 78 pairs are listed, sorted by "
            "Holm-adjusted p.", "",
            md(pw[["tool_a", "tool_b", "median_diff", "wins_a", "wins_b", "cliffs_delta",
                   "magnitude", "p", "p_holm"]], "{:.3g}", index=False), ""]

# 12 pK
pk = pd.read_csv(R / "sensitivity/df_pk.tsv", sep="\t").pivot(index="pK", columns="dataset",
                                                             values="auprc")
pk.index = [f"{x:g}" for x in pk.index]; pk.index.name = "pK"
auto = d[d.tool == "doubletfinder"].set_index("dataset").auprc
out += ["## 12. DoubletFinder pK sensitivity",
        "",
        "AUPRC with pK fixed. Bottom row: the main run, where pK is chosen automatically "
        "(BCmvn), which picked 0.005 (pbmc-1C-dm), 0.13 (pbmc-2stim-dm) and 0.3 (pbmc-ch).", "",
        md(pd.concat([pk, pd.DataFrame([auto[pk.columns]], index=["automatic"])])), ""]

# 13 failures
allm = pd.concat([pd.read_csv(R / "metrics.tsv", sep="\t"), pd.read_csv(R / "scaling_metrics.tsv", sep="\t")])
fail = allm[allm.status != "ok"][["tool", "dataset", "rate_mult", "error"]]
fail["error"] = fail.error.str.replace("|", "/", regex=False).str.slice(0, 140)
n_total = len(allm)
out += ["## 13. Failed runs", "",
        f"{len(fail)} of {n_total} runs failed (main run, robustness and scaling together). "
        "The `error` column is the last lines of the log. For both Chord failures, the actual "
        "error is earlier in the log: `overkillDB2 -> sample(): cannot take a sample larger than "
        "the population when 'replace = FALSE'` (2× the labeled rate is 0.62 and 0.75).", "",
        md(fail, "{:g}", index=False) if len(fail) else "None.", ""]

# 14 raw
out += ["## 14. Raw files", "", "| file | content |", "|---|---|",
        "| `results/metrics.tsv` | One row per run (tool × dataset × rate multiplier): every accuracy metric, wall time, peak memory and status |",
        "| `results/scaling_metrics.tsv` | The same, for the scaling subsamples |",
        "| `results/bench/<tool>/<ds>/*.tsv` | Raw Snakemake benchmark output (time, RSS, CPU) |",
        "| `results/stats/*.tsv` | Ranks, Friedman test, pairwise tests, agreement, rate estimation |",
        "| `results/robustness_summary.tsv`, `results/scaling_summary.tsv` | Summary tables for sections 7 and 9 |",
        "| `results/sensitivity/df_pk.tsv` | DoubletFinder pK sensitivity |",
        "| `results/pred/` (not in git, about 0.3 GB) | Per-droplet scores and calls; rebuild them with the pipeline |",
        ""]

(ROOT / "report").mkdir(exist_ok=True)
(ROOT / "report/data.md").write_text("\n".join(out))
print("wrote report/data.md", sum(len(x) for x in out), "chars")
